def bits(row):
    value = 0
    for x, pixel in enumerate(row):
        if pixel == "#":
            value |= 1 << x
    return value


def main():
    missing = [n for n in range(32, 127) if n not in GLYPHS]
    if missing:
        sys.exit("missing glyphs: " + " ".join(str(n) for n in missing))
    rows_out = []
    for n in range(32, 127):
        parts = GLYPHS[n].split()
        if len(parts) != 7 or any(len(part) != 5 or set(part) - set(".#") for part in parts):
            sys.exit(f"bad glyph {n} {GLYPHS[n]!r}")
        rows_out.append(", ".join(str(bits(part)) for part in parts) + ", 0")
    if bits(GLYPHS[62].split()[0]) != 1:
        sys.exit("greater-than row 0 must be the left pixel")
    text = "\n".join(
        [
            "/* SPDX-License-Identifier: Apache-2.0 */",
            "/* Generated by font6x8.py. ASCII 32..126, eight rows, bit 0 is left. */",
            "#pragma once",
            "#include <stdint.h>",
            "static const uint8_t font6x8[95 * 8] = {",
            "    " + ",\n    ".join(rows_out),
            "};",
            "",
        ]
    )
    path = pathlib.Path(__file__).with_name("font6x8.h")
    path.write_text(text)
    print(path)


if __name__ == "__main__":
    main()
